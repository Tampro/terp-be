package com.terp.erp.recruitment.offer;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import jakarta.validation.constraints.NotNull;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import com.terp.erp.exception.ApiException;
import com.terp.erp.outbox.OutboxPublisher;
import com.terp.erp.outbox.Payload;
import com.terp.erp.recruitment.candidate.Candidate;
import com.terp.erp.recruitment.candidate.CandidateService;
import com.terp.erp.recruitment.client.EmployeeClient;
import com.terp.erp.recruitment.common.ERecruitmentError;

import java.time.Clock;
import java.time.LocalDate;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Convert to Employee: an ACCEPTED offer (REC_060) of a candidate not yet converted (REC_061) becomes an employee of
 * employee-service, created as the caller (EMPLOYEE_CREATE there, IAM_USER_CREATE for the login). employee-service is
 * called before anything is written here, so a refusal (relayed as is) or an outage (REC_012) leaves this side
 * untouched. Not retried: creating an employee is not idempotent. The reverse gap remains: if saving here fails after
 * employee-service answered, the employee exists without the link (no compensation, like IAM user creation).
 * TODO: the welcome email waits for the notification service.
 */
@Service
@RequiredArgsConstructor
public class OfferConversionService {
    private final OfferService offerService;
    private final CandidateService candidateService;
    private final EmployeeClient employees;
    private final Clock clock;
    private final OutboxPublisher outbox;

    /** Same values as employee-service's EEmploymentType / EEmployeeStatus. */
    public enum EEmploymentType { FULL_TIME, PART_TIME, CONTRACT, INTERN, TEMPORARY }

    public enum EEmployeeStatus { ACTIVE, INACTIVE, PROBATION, TERMINATED }

    public record ConvertForm(
            @Schema(description = "employee-service branch", example = "1") Long branchId,
            @Schema(description = "employee-service department (needs branchId); omitted = the offer's", example = "3")
            Long departmentId,
            @Schema(description = "employee-service designation (needs the department)", example = "4")
            Long designationId,
            @Schema(description = "Omitted = the offer start date (today when the offer has none)",
                    example = "2027-01-04") LocalDate dateOfJoining,
            @Schema(example = "FULL_TIME", requiredMode = Schema.RequiredMode.REQUIRED) @NotNull
            EEmploymentType employmentType,
            @Schema(description = "Omitted = PROBATION") EEmployeeStatus employeeStatus,
            @Schema(description = "Code for the biometric device, unique in the company", example = "EMP001")
            @Size(max = 50) @Pattern(regexp = "[A-Za-z0-9._-]*") String employeeCode,
            @Schema(description = "First password, changed at the first login; omitted = generated by IAM")
            @Size(min = 8, max = 128) String password) {
    }

    public record Converted(String offerId, String candidateId, String employeeId, Candidate.EStatus candidateStatus) {
    }

    @Transactional
    public Converted convert(Long offerId, ConvertForm f) {
        Offer o = offerService.require(offerId);
        if (o.getStatus() != Offer.EStatus.ACCEPTED) {
            throw ApiException.badRequest(ERecruitmentError.REC_060);
        }
        Candidate c = candidateService.require(o.getCandidateId());
        if (c.getEmployeeId() != null) {
            throw ApiException.badRequest(ERecruitmentError.REC_061);
        }
        EmployeeClient.Employee e = employees.create(o.getCompanyId(), employeeForm(o, c, f));
        c.setEmployeeId(Long.valueOf(e.id()));
        c.setStatus(Candidate.EStatus.HIRED);
        outbox.publish(o.getCompanyId(), "recruitment.candidate.converted", "CANDIDATE", c.getId(), Payload.of(
                "candidateId", c.getId(), "title", c.fullName(), "name", c.fullName(), "offerId", o.getId(),
                "employeeId", e.id(), "jobPostingId", o.getJobPostingId()));
        return new Converted(o.getId().toString(), c.getId().toString(), e.id(), c.getStatus());
    }

    /** employee-service EmployeeCreateForm: email (also the login), password, profile. */
    Map<String, Object> employeeForm(Offer o, Candidate c, ConvertForm f) {
        LocalDate joining = f.dateOfJoining() != null ? f.dateOfJoining()
                : o.getStartDate() != null ? o.getStartDate() : LocalDate.now(clock.withZone(OfferService.ZONE));
        Map<String, Object> profile = new LinkedHashMap<>();
        profile.put("fullName", c.fullName());
        profile.put("employeeCode", f.employeeCode());
        profile.put("phone", c.getPhone());
        profile.put("dateOfBirth", c.getDateOfBirth() == null ? null : c.getDateOfBirth().toString());
        profile.put("gender", c.getGender() == null ? null : c.getGender().name());
        profile.put("branchId", f.branchId());
        profile.put("departmentId", f.departmentId() != null ? f.departmentId() : o.getDepartmentId());
        profile.put("designationId", f.designationId());
        profile.put("dateOfJoining", joining.toString());
        profile.put("employmentType", f.employmentType().name());
        // TODO(assumption): a converted candidate starts on PROBATION unless the form says otherwise — confirm with BA
        profile.put("status", (f.employeeStatus() == null ? EEmployeeStatus.PROBATION : f.employeeStatus()).name());
        profile.put("addressLine1", c.getAddress());
        profile.put("city", c.getCity());
        profile.put("state", c.getState());
        profile.put("country", c.getCountry());
        profile.put("postalCode", c.getZipCode());
        Map<String, Object> form = new LinkedHashMap<>();
        form.put("email", c.getEmail());
        form.put("password", f.password());
        form.put("profile", profile);
        return form;
    }
}
