package com.terp.erp.employee.client;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import com.terp.erp.employee.common.EEmployeeError;
import com.terp.erp.employee.config.EmployeeProperties;
import com.terp.erp.security.CurrentUser;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/** Login accounts of employees live in IAM (PO, 2026-11-19: employee-service calls IAM as the caller). */
@Slf4j
@Component
public class IamClient {
    /** Role every new employee account gets; COMPANY_ADMIN and HR are granted in IAM. */
    static final String EMPLOYEE_ROLE = "EMPLOYEE";

    /** @param maxEmployees null = no limit */
    public record CompanyContext(Long companyId, String name, Integer maxEmployees) {
    }

    private final CallerHttp http;

    public IamClient(EmployeeProperties props, ObjectMapper mapper) {
        this.http = new CallerHttp(props.iamServiceUrl(), mapper, EEmployeeError.EMP_014, "IAM");
    }

    public CompanyContext company(Long companyId) {
        JsonNode d = http.call(c -> c.get().uri(uri("/api/v1/me/company", companyId))).path("data");
        return new CompanyContext(d.path("companyId").asLong(), d.path("name").asText(""),
                d.path("maxEmployees").isNumber() ? d.path("maxEmployees").asInt() : null);
    }

    /**
     * Creates the account (username = email) with the EMPLOYEE role. The password is the administrator's choice or
     * generated by IAM; either way it is temporary and IAM emails it. Returns the IAM user id.
     */
    public Long createAccount(Long companyId, String email, String fullName, String password) {
        Map<String, Object> body = new HashMap<>();
        body.put("username", email);
        body.put("email", email);
        body.put("fullName", fullName);
        body.put("roleIds", List.of());
        body.put("roleCodes", Set.of(EMPLOYEE_ROLE));
        if (password != null && !password.isBlank()) {
            body.put("password", password);
        }
        JsonNode d = http.call(c -> c.post().uri(uri("/api/v1/iam/users", companyId))
                .contentType(MediaType.APPLICATION_JSON).body(body)).path("data");
        return d.path("user").path("id").asLong();
    }

    public void setLoginEnabled(Long userId, boolean enabled) {
        http.call(c -> c.put().uri("/api/v1/iam/users/{id}/status", userId).contentType(MediaType.APPLICATION_JSON)
                .body(Map.of("status", enabled ? "ACTIVE" : "LOCKED")));
    }

    public void changePassword(Long userId, String newPassword) {
        http.call(c -> c.put().uri("/api/v1/iam/users/{id}/password", userId).contentType(MediaType.APPLICATION_JSON)
                .body(Map.of("newPassword", newPassword)));
    }

    /** Compensation after a failed employee insert: the account must not stay usable. Best effort, logged. */
    public void lockQuietly(Long userId) {
        try {
            setLoginEnabled(userId, false);
        } catch (RuntimeException e) {
            log.error("Account {} was created but the employee was not; locking it failed too: {}", userId,
                    e.getClass().getSimpleName());
        }
    }

    /** Only a super admin may name a company; for a company user IAM uses their own company anyway. */
    private static String uri(String path, Long companyId) {
        return CurrentUser.get().superAdmin() && companyId != null ? path + "?companyId=" + companyId : path;
    }
}
