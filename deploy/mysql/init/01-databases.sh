#!/bin/bash
# Runs once, on an empty data volume. One database per service (microservices own their data) plus Keycloak's.
set -euo pipefail

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE DATABASE IF NOT EXISTS erp_iam CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_media CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_employee CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_attendance CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_recruitment CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_payroll CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_asset CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_meeting CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_document CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_inventory CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_commerce CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_accounting CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_crm CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS erp_project CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS keycloak CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${IAM_DB_USERNAME}'@'%' IDENTIFIED BY '${IAM_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${KC_DB_USERNAME}'@'%' IDENTIFIED BY '${KC_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_iam.* TO '${IAM_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${MEDIA_DB_USERNAME}'@'%' IDENTIFIED BY '${MEDIA_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_media.* TO '${MEDIA_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${EMPLOYEE_DB_USERNAME}'@'%' IDENTIFIED BY '${EMPLOYEE_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_employee.* TO '${EMPLOYEE_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${ATTENDANCE_DB_USERNAME}'@'%' IDENTIFIED BY '${ATTENDANCE_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_attendance.* TO '${ATTENDANCE_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${RECRUITMENT_DB_USERNAME}'@'%' IDENTIFIED BY '${RECRUITMENT_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_recruitment.* TO '${RECRUITMENT_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${PAYROLL_DB_USERNAME}'@'%' IDENTIFIED BY '${PAYROLL_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_payroll.* TO '${PAYROLL_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${ASSET_DB_USERNAME}'@'%' IDENTIFIED BY '${ASSET_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_asset.* TO '${ASSET_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${MEETING_DB_USERNAME}'@'%' IDENTIFIED BY '${MEETING_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_meeting.* TO '${MEETING_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${DOCUMENT_DB_USERNAME}'@'%' IDENTIFIED BY '${DOCUMENT_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_document.* TO '${DOCUMENT_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${INVENTORY_DB_USERNAME}'@'%' IDENTIFIED BY '${INVENTORY_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_inventory.* TO '${INVENTORY_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${COMMERCE_DB_USERNAME}'@'%' IDENTIFIED BY '${COMMERCE_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_commerce.* TO '${COMMERCE_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${ACCOUNTING_DB_USERNAME}'@'%' IDENTIFIED BY '${ACCOUNTING_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_accounting.* TO '${ACCOUNTING_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${CRM_DB_USERNAME}'@'%' IDENTIFIED BY '${CRM_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_crm.* TO '${CRM_DB_USERNAME}'@'%';
CREATE USER IF NOT EXISTS '${PROJECT_DB_USERNAME}'@'%' IDENTIFIED BY '${PROJECT_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON erp_project.* TO '${PROJECT_DB_USERNAME}'@'%';
GRANT ALL PRIVILEGES ON keycloak.* TO '${KC_DB_USERNAME}'@'%';
FLUSH PRIVILEGES;
SQL
